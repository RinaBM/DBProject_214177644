-- ============================================================
-- קובץ: 08_MainProgram2_PayBookings.sql
-- שלב ד' - תוכנית ראשית מספר 2
--
-- מטרת התוכנית:
-- 1. לבחור לקוח שיש לו הזמנות שעדיין לא שולמו.
-- 2. לזמן פונקציה שמחזירה Ref Cursor עם ההזמנות הלא משולמות שלו.
-- 3. לזמן פרוצדורה שמעדכנת את ההזמנות האלו כ"שולמו".
-- 4. להציג בסוף את טבלת התשלומים ואת ההזמנות האחרונות.
--
-- חשוב:
-- PostgreSQL לא מאפשר להשתמש ב-SELECT ישירות בתוך CALL,
-- לכן קודם שומרים את מזהה הלקוח במשתנה v_c_id,
-- ורק אחר כך קוראים לפרוצדורה.
-- ============================================================


DO $$
DECLARE
    -- משתנה שישמור את מזהה הלקוח שנבחר
    v_c_id INTEGER;

    -- שם הסמן שנשלח לפונקציה שמחזירה Ref Cursor
    v_cursor_name TEXT := 'customer_unpaid_cursor';

BEGIN
    -- ------------------------------------------------------------
    -- שלב 1:
    -- נבחר לקוח שיש לו לפחות הזמנה אחת שלא שולמה.
    -- אצלנו b_status = FALSE אומר שההזמנה עדיין לא שולמה.
    -- ------------------------------------------------------------
    SELECT c.c_id
    INTO v_c_id
    FROM customer c
    JOIN bookings b ON b.c_id = c.c_id
    WHERE b.b_status = FALSE
    ORDER BY c.c_id
    LIMIT 1;


    -- ------------------------------------------------------------
    -- אם לא מצאנו לקוח עם הזמנות לא משולמות,
    -- נבחר פשוט את הלקוח הראשון במערכת.
    -- זה מונע מצב שבו המשתנה נשאר NULL.
    -- ------------------------------------------------------------
    IF v_c_id IS NULL THEN
        SELECT c.c_id
        INTO v_c_id
        FROM customer c
        ORDER BY c.c_id
        LIMIT 1;
    END IF;


    -- ------------------------------------------------------------
    -- אם עדיין לא נמצא לקוח בכלל,
    -- סימן שטבלת customer ריקה ולכן נזרוק חריגה.
    -- ------------------------------------------------------------
    IF v_c_id IS NULL THEN
        RAISE EXCEPTION 'No customer was found in the database';
    END IF;


    -- ------------------------------------------------------------
    -- הדפסה למסך כדי שנוכל לצלם לדוח
    -- איזה לקוח נבחר בתוכנית הראשית.
    -- ------------------------------------------------------------
    RAISE NOTICE 'Main program 2 selected customer id: %', v_c_id;


    -- ------------------------------------------------------------
    -- שלב 2:
    -- קריאה לפונקציה שמחזירה Ref Cursor.
    -- הפונקציה מקבלת מזהה לקוח ושם Cursor,
    -- ופותחת Cursor עם ההזמנות הלא משולמות של אותו לקוח.
    --
    -- כאן אנחנו מזמנים את הפונקציה כחלק מהדרישה:
    -- כל תוכנית ראשית צריכה לזמן פונקציה אחת.
    -- ------------------------------------------------------------
    PERFORM fn_customer_unpaid_bookings(v_c_id, v_cursor_name);

    RAISE NOTICE 'Function fn_customer_unpaid_bookings was called for customer id: %', v_c_id;


    -- ------------------------------------------------------------
    -- שלב 3:
    -- קריאה לפרוצדורה שמטפלת בתשלום.
    -- הפרוצדורה עוברת על כל ההזמנות הלא משולמות של הלקוח,
    -- מעדכנת אותן ל-b_status = TRUE,
    -- ומוסיפה רשומות לטבלת payment_log.
    --
    -- כאן אנחנו מזמנים את הפרוצדורה כחלק מהדרישה:
    -- כל תוכנית ראשית צריכה לזמן פרוצדורה אחת.
    -- ------------------------------------------------------------
    CALL pr_pay_customer_bookings(v_c_id);

    RAISE NOTICE 'Procedure pr_pay_customer_bookings was called for customer id: %', v_c_id;


-- ------------------------------------------------------------
-- טיפול בשגיאות:
-- אם משהו נכשל במהלך התוכנית, נציג הודעת שגיאה ברורה.
-- זה גם עוזר להראות שימוש ב-Exception.
-- ------------------------------------------------------------
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'Error in MainProgram2_PayBookings: %', SQLERRM;
END;
$$;


-- ============================================================
-- הצגת תוצאות אחרי הרצת התוכנית הראשית
-- ============================================================


-- ------------------------------------------------------------
-- הצגת רשומות התשלום האחרונות.
-- אם הפרוצדורה עבדה, אמורות להופיע כאן רשומות חדשות.
-- את זה אפשר לצלם לדוח כהוכחה שהטבלה התעדכנה.
-- ------------------------------------------------------------
SELECT *
FROM payment_log
ORDER BY payment_id DESC
LIMIT 10;


-- ------------------------------------------------------------
-- הצגת ההזמנות האחרונות.
-- כאן אפשר לראות שהעמודה b_status השתנתה ל-TRUE,
-- כלומר ההזמנות סומנו כשולמו.
-- ------------------------------------------------------------
SELECT *
FROM bookings
ORDER BY b_id DESC
LIMIT 10;