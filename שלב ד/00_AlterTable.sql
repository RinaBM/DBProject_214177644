-- טבלת היסטוריית מחירים של טיולים.
-- כל פעם שמחיר בטבלת tour משתנה, הטריגר יוסיף לכאן רשומה.
CREATE TABLE IF NOT EXISTS tour_price_history (
    history_id SERIAL PRIMARY KEY,              -- מזהה אוטומטי של רשומת ההיסטוריה
    t_name VARCHAR(255) NOT NULL,               -- שם הטיול שהמחיר שלו השתנה
    old_price INTEGER,                          -- המחיר הישן לפני העדכון
    new_price INTEGER,                          -- המחיר החדש אחרי העדכון
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP -- תאריך ושעת השינוי
);

-- טבלת יומן תשלומים.
-- כל פעם שפרוצדורת התשלום מסמנת הזמנה כשולמה, היא מוסיפה לכאן רשומה.
CREATE TABLE IF NOT EXISTS payment_log (
    payment_id SERIAL PRIMARY KEY,              -- מזהה אוטומטי של תשלום ביומן
    c_id INTEGER NOT NULL,                      -- מזהה הלקוח ששילם
    b_id INTEGER NOT NULL,                      -- מזהה ההזמנה ששולמה
    amount NUMERIC,                             -- סכום התשלום
    paid_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,-- תאריך ושעת התשלום
    note TEXT                                   -- הערה שמסבירה מי יצר את הרשומה
);
